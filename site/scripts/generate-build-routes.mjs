// Writes one route folder per live build into app/builds/.
// Runs before every dev and build (see the prebuild script in package.json).
// Static export needs a real route folder for each page, so these are made
// from the builds folder every time. Nothing here is hand edited or committed.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { getAllBuilds } from "../lib/builds.mjs";

const siteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const routesRoot = path.join(siteRoot, "app", "builds");

fs.rmSync(routesRoot, { recursive: true, force: true });

const builds = getAllBuilds();

for (const build of builds) {
  const dir = path.join(routesRoot, build.slug);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    path.join(dir, "page.tsx"),
    `// Generated by scripts/generate-build-routes.mjs. Do not edit.\n` +
      `import BuildPage, { buildMetadata } from "../../../components/BuildPage";\n\n` +
      `const slug = ${JSON.stringify(build.slug)};\n\n` +
      `export function generateMetadata() {\n` +
      `  return buildMetadata(slug);\n` +
      `}\n\n` +
      `export default function Page() {\n` +
      `  return <BuildPage slug={slug} />;\n` +
      `}\n`,
    "utf8"
  );
}

console.log(
  builds.length === 0
    ? "generate-build-routes: 0 live builds, no build pages generated"
    : `generate-build-routes: ${builds.length} page(s) -> ${builds
        .map((build) => build.slug)
        .join(", ")}`
);
